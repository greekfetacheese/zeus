#[derive(Debug)]
pub enum RegistryPinError {
   Unpinned {
      path: String,
   },
   Mismatch {
      path: String,
      expected: String,
      actual: String,
   },
   TooLarge {
      path: String,
      size: usize,
   },
}

impl std::fmt::Display for RegistryPinError {
   fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
      match self {
         Self::Unpinned { path } => write!(f, "no SHA-256 pin for {path}"),
         Self::Mismatch {
            path,
            expected,
            actual,
         } => write!(
            f,
            "SHA-256 mismatch for {path}: expected {expected}, got {actual}"
         ),
         Self::TooLarge { path, size } => {
            write!(
               f,
               "registry JSON {path} is too large ({size} bytes)"
            )
         }
      }
   }
}

impl std::error::Error for RegistryPinError {}

fn decode_sha256_hex(hex: &str) -> Option<[u8; 32]> {
   if hex.len() != 64 {
      return None;
   }
   let mut out = [0u8; 32];
   for i in 0..32 {
      out[i] = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16).ok()?;
   }
   Some(out)
}

fn pin_digest(registry_path: &str) -> Option<[u8; 32]> {
   let hex = PINS.iter().find(|(p, _)| *p == registry_path).map(|(_, hex)| *hex)?;
   decode_sha256_hex(hex)
}

/// True when `registry_path` has a pin in [`PINS`].
pub fn is_registry_file_pinned(registry_path: &str) -> bool {
   pin_digest(registry_path).is_some()
}

/// Paths in the pin table (same set as the embedded pack).
pub fn pinned_registry_paths() -> impl Iterator<Item = &'static str> {
   PINS.iter().map(|(path, _)| *path)
}

/// Reject path traversal / absolute URLs before any fetch.
pub fn is_allowed_registry_path(path: &str) -> bool {
   if path.is_empty() || path.starts_with('/') || path.contains('\\') {
      return false;
   }
   if !path.ends_with(".json") {
      return false;
   }
   let mut parts: Vec<&str> = Vec::new();
   for seg in path.split('/') {
      if seg.is_empty() || seg == "." || seg == ".." {
         return false;
      }
      parts.push(seg);
   }
   match parts[0] {
      "index.eip712.json" | "index.calldata.json" if parts.len() == 1 => true,
      "registry" | "ercs" if parts.len() >= 2 => true,
      _ => false,
   }
}

/// SHA-256 of `data` must match the pin for this registry path.
pub fn verify_registry_pin(registry_path: &str, data: &[u8]) -> Result<(), RegistryPinError> {
   if data.len() > MAX_REGISTRY_JSON_BYTES {
      return Err(RegistryPinError::TooLarge {
         path: registry_path.to_string(),
         size: data.len(),
      });
   }
   let expected = pin_digest(registry_path).ok_or_else(|| RegistryPinError::Unpinned {
      path: registry_path.to_string(),
   })?;
   let actual: [u8; 32] = Sha256::digest(data).into();
   if actual != expected {
      return Err(RegistryPinError::Mismatch {
         path: registry_path.to_string(),
         expected: actual_to_hex(&expected),
         actual: actual_to_hex(&actual),
      });
   }
   Ok(())
}

fn actual_to_hex(bytes: &[u8; 32]) -> String {
   let mut s = String::with_capacity(64);
   for b in bytes {
      s.push_str(&format!("{b:02x}"));
   }
   s
}

#[cfg(test)]
mod tests {
   use super::*;
   use std::collections::HashSet;

   #[test]
   fn pin_table_is_well_formed() {
      assert_eq!(PINS.len(), REGISTRY_PIN_COUNT);
      let mut keys = HashSet::new();
      for &(path, hex) in PINS {
         assert!(is_allowed_registry_path(path), "{path}");
         assert_eq!(hex.len(), 64, "{path}");
         assert!(
            hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')),
            "{path} pin is not lowercase hex"
         );
         assert!(
            pin_digest(path).is_some(),
            "pin {path} does not decode"
         );
         assert!(keys.insert(path), "duplicate pin {path}");
      }
      assert!(is_registry_file_pinned("index.eip712.json"));
      assert!(is_registry_file_pinned("index.calldata.json"));
      assert!(is_registry_file_pinned(
         "registry/uniswap/eip712-uniswap-permit2.json"
      ));
      assert!(is_registry_file_pinned(
         "ercs/eip712-erc2612-permit.json"
      ));
      assert!(is_registry_file_pinned(
         "ercs/calldata-erc4626-vaults.json"
      ));
   }

   #[test]
   fn unpinned_and_disallowed_paths_are_rejected() {
      let blob = [0xABu8; 300];
      let err = verify_registry_pin("registry/evil/malware.json", &blob).unwrap_err();
      assert!(matches!(err, RegistryPinError::Unpinned { .. }));
      assert!(!is_allowed_registry_path(
         "https://evil.example/x.json"
      ));
      assert!(!is_allowed_registry_path("../index.eip712.json"));
      assert!(!is_allowed_registry_path(
         "registry/../index.eip712.json"
      ));
      assert!(!is_allowed_registry_path("/etc/passwd.json"));
      assert!(!is_allowed_registry_path("tools/foo.json"));
   }

   #[test]
   fn mismatch_is_rejected() {
      let blob = [0xABu8; 300];
      let err = verify_registry_pin("index.eip712.json", &blob).unwrap_err();
      assert!(matches!(err, RegistryPinError::Mismatch { .. }));
   }

   #[test]
   fn too_large_is_rejected() {
      let blob = vec![0u8; MAX_REGISTRY_JSON_BYTES + 1];
      let err = verify_registry_pin("index.eip712.json", &blob).unwrap_err();
      assert!(matches!(err, RegistryPinError::TooLarge { .. }));
   }
}
